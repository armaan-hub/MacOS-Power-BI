class BlankTextGridTests(unittest.TestCase):
    """The rules derived from the measured grid (see _isnumber_blank_text in analytics_studio/measures.py)."""

    def test_grid_iserror_and_isnumber(self) -> None:
        wrong = []
        for expression, code in GRID:
            error = dax.local(f"ISERROR({expression})")
            number = dax.local(f"ISNUMBER({expression})")
            want_error = "True" if code[0] == "T" else "False"
            if error != want_error:
                wrong.append((f"ISERROR({expression})", want_error, error))
            if code[1] == "E":
                if not number.startswith("LOCAL-REJECT"):
                    wrong.append((f"ISNUMBER({expression})", "error", number))
            elif number != ("True" if code[1] == "T" else "False"):
                wrong.append((f"ISNUMBER({expression})", code[1], number))
        self.assertEqual(wrong, [])

    def test_fresh_shapes(self) -> None:
        wrong = [(expression, want, dax.local(expression)) for expression, want in FRESH if dax.local(expression) != want]
        self.assertEqual(wrong, [])

    def test_unmeasured_nesting_is_refused(self) -> None:
        # a data-dependent logical BLANK beside a text inside a deeper expression is not in the grid: refuse, do not guess
        self.assertTrue(dax.local('ISNUMBER((MAX(Facts[Quantity])>0&&"")*("a"*2))').startswith("LOCAL-REJECT"))

    def test_rule_table(self) -> None:
        from analytics_studio.measures import _isnumber_blank_text as rule
        self.assertEqual(rule("*", "K1", "folded", True), "T")
        self.assertEqual(rule("*", "K2", "folded", True), "F")
        self.assertEqual(rule("*", "K1", "runtime", True), "F")
        self.assertEqual(rule("+", "K1", "data", False), "T")
        self.assertEqual(rule("+", "K0", "data", False), "E")
        self.assertEqual(rule("^", "K0", "folded", True), "E")
        self.assertEqual(rule("^", "K0", "folded", False), "T")


if __name__ == "__main__":
    unittest.main()
