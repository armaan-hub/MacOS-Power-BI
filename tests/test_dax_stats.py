@pytest.mark.parametrize("expression,expected", VALUES)
def test_values_match_power_bi(expression: str, expected: str) -> None:
    value = measure(expression)
    if expected in ("True", "False"):
        assert str(value) == expected
        return
    answer = Decimal(expected)
    assert abs(Decimal(value) - answer) <= Decimal("1e-9") * max(Decimal(1), abs(answer)), (expression, value, expected)


