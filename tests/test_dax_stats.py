def test_integer_arguments_round_half_away_from_zero() -> None:
    # degrees of freedom / sample size / event count are rounded, not truncated (Power BI: df 2.5 -> 3, 2.4 -> 2)
    assert measure("T.DIST(2.5,2.9,TRUE())") == measure("T.DIST(2.5,3.1,TRUE())")
    assert measure("CONFIDENCE.NORM(0.05,2,2.5)") == measure("CONFIDENCE.NORM(0.05,2,3)")
    assert measure("POISSON.DIST(1.5,3,FALSE())") == measure("POISSON.DIST(2,3,FALSE())")
