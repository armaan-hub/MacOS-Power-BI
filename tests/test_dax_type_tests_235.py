def _answer(function: str, text: str) -> bool | None:
    return rule.answer(function, measures.parse_expression(text), COLUMNS)


def test_rule_answers_by_static_type_when_the_value_cannot_change_it() -> None:
    assert _answer("ISTEXT", '(VAR y=VALUE("x") RETURN y)&("b")') is True  # text, never BLANK because of the literal
    assert _answer("ISNUMBER", '(MAX(Facts[Note]))+("a"+1)') is True  # double, never BLANK because of the "a"+1 operand
    assert _answer("ISLOGICAL", '(MAX(Facts[Sales]))+((-1)^0.5)') is False  # a number is never True/False


def test_rule_refuses_when_a_blank_would_change_the_answer() -> None:
    assert _answer("ISNUMBER", "FACT(-1)") is None  # FACT(-1) can be BLANK as far as the engine knows
    assert _answer("ISDOUBLE", "BLANK()^BLANK()") is None
    assert _answer("ISSTRING", 'VAR v=SIGN("s") RETURN v&""') is None  # a bare VAR is not followed


def test_rule_keeps_a_folded_part_outside_a_var_refused() -> None:
    assert _answer("ISNUMBER", 'VALUE("x")+1') is None
    assert _answer("ISNUMBER", 'DATEVALUE("q")+1') is None
    assert _answer("ISTEXT", 'LOG(MAX(Facts[Note]),"a")') is None


def test_formerly_locked_shapes_are_answered() -> None:
    saved = {
        "ISNUMBER((2.5)+((-1)^0.5))": "True",
        'ISNONTEXT(NOT("a"))': "True",
        'ISLOGICAL(MAX(Facts[Note])&""&&1)': "True",
    }
    for expression, expected in saved.items():
        assert local(expression) == expected, expression
    assert _answer("ISNUMBER", "(2.5)+((-1)^0.5)") is True  # the saved Power BI answer


def test_rule_never_touches_ordinary_answers() -> None:
    assert local("ISNUMBER(1)") == "True"
    assert local('ISTEXT("a")') == "True"
    assert local("ISLOGICAL(1=1)") == "True"
