    def test_comments_between_table_and_column(self) -> None:
        self.assertEqual("15", dax.local("SUM(Facts/*c*/[Quantity])"))
        self.assertEqual("15", dax.local("SUM(Facts /* c */ [Quantity])"))
        self.assertEqual("15", dax.local("SUM('Facts'/*c*/[Quantity])"))

    def test_strict_equality(self) -> None:
        self.assertEqual("False", dax.local("COUNTROWS(Facts)==5"))
        self.assertEqual("True", dax.local("COUNTROWS(Facts)==6"))
        self.assertTrue(dax.local('(1)==("a")').startswith("LOCAL-REJECT"))
        self.assertTrue(dax.local("1==1==1").startswith("LOCAL-REJECT"))

    def test_text_as_condition(self) -> None:
        self.assertEqual("2", dax.local('IF("TRUE",2,3)'))
        self.assertEqual("3", dax.local('IF("",2,3)'))
        self.assertEqual("2", dax.local('IF("1",2,3)'))
        self.assertTrue(dax.local('IF("yes",2,3)').startswith("LOCAL-REJECT"))

    def test_time_only_text(self) -> None:
        self.assertEqual("13", dax.local('HOUR("13:45")'))
        self.assertEqual("13", dax.local('HOUR("1:45 PM")'))
        self.assertEqual("0", dax.local('HOUR("12:00 AM")'))
        self.assertEqual("30", dax.local('SECOND("13:45:30")'))
        self.assertTrue(dax.local('HOUR("24:00")').startswith("LOCAL-REJECT"))

    def test_function_edges(self) -> None:
        self.assertEqual("1234.56", dax.local("TRUNC(1234.567,1.9)"))
        self.assertEqual("1234.5", dax.local("TRUNC(1234.567,1.1)"))
        self.assertEqual("4", dax.local("ISO.CEILING(2.1,-2)"))
        self.assertEqual("0", dax.local("PERCENTILE.INC(Facts[Quantity],BLANK())"))
        self.assertTrue(dax.local("PERCENTILE.EXC(Facts[Quantity],BLANK())").startswith("LOCAL-REJECT"))

    def test_unmodelled_stays_refused(self) -> None:
        for expr in STAYS_REFUSED:
            self.assertTrue(dax.local(expr).startswith("LOCAL-REJECT"), expr)


