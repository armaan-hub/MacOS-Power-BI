"""Stage D1d probe tables for the Power Query step differential tool (Part D, item 1).

Two data-driven tables, each step run on the step engine and on the store, and each answer must be the same:
- the malformed-parameter table: 667 steps (7 ops x every parameter set to each of 33 odd values, plus one extra key
  per op), run on one 2-row, 3-column table;
- the shape table (unpivot, transpose, promote and demote, split into rows, split by positions): 336 steps on several
  small tables, 323 the same and 13 refused by name (an output column named `__rn`, the store's own load-order column).
Both tables are generated by the functions below (no saved answers). The hand-checked rule tests are in
test_pq_store_diff_tool_d1d.py.
"""

from __future__ import annotations

from collections import Counter
from typing import Any

from tests.test_pq_store_diff_tool import _run_items

PARAM_HEADERS = ["a", "b", "c"]
PARAM_ROWS = [["1", "x|y", "3"], ["", "p", "q"]]
PARAM_VALUES: list[Any] = [
    None, "", "a", "b", "zz", " a", "a ", " ", 0, 1, -1, 2, 3, True, False, 1.5, [], ["a"], ["a", "b"], ["a", "a"],
    ["a", "zz"], [0], [0, 1], [0, 0], [1, 0], [0, 2, 1], [-1, 2], [1, 2], [0, 1.5], [0, "1"], [0, True], [0, 10**9],
    {"x": 1},
]
PARAM_BASES: dict[str, dict[str, Any]] = {
    "unpivot_columns": {"op": "unpivot_columns", "columns": ["b"], "attribute_name": "at", "value_name": "va"},
    "unpivot_other_columns": {"op": "unpivot_other_columns", "columns": ["a"], "attribute_name": "at", "value_name": "va"},
    "split_column_to_rows": {"op": "split_column_to_rows", "column": "b", "delimiter": "|"},
    "split_column_by_positions": {"op": "split_column_by_positions", "column": "b", "positions": [0, 1]},
    "extract_text_by_delimiter": {
        "op": "extract_text_by_delimiter", "column": "b", "delimiter": "|", "side": "before", "occurrence": 0,
    },
    "extract_text_between_delimiters": {
        "op": "extract_text_between_delimiters", "column": "b", "start_delimiter": "x", "end_delimiter": "y",
        "start_occurrence": 0, "end_occurrence": 0,
    },
    "promote_headers": {"op": "promote_headers", "promote_all_scalars": True},
}


def param_items() -> list[dict[str, Any]]:
    """Every parameter of every base step set to each odd value (None removes it), plus one extra key per op."""
    items: list[dict[str, Any]] = []
    for op, base in PARAM_BASES.items():
        for key in [k for k in base if k != "op"]:
            for value in PARAM_VALUES:
                step = dict(base)
                if value is None:
                    step.pop(key, None)
                else:
                    step[key] = value
                items.append({"id": f"{len(items):04d} {op} {key}={value!r}", "step": step})
        items.append({"id": f"{len(items):04d} {op} extra", "step": {**base, "extra": 1}})
    return items


def _run_group(headers: list[str], rows: list[list[str]], steps: list[tuple[str, dict[str, Any]]]) -> list[dict[str, Any]]:
    items = [{"id": f"{n:03d} {tag}", "step": step} for n, (tag, step) in enumerate(steps)]
    return _run_items({"headers": headers, "rows": rows}, items)["results"]


def shape_groups() -> list[tuple[list[str], list[list[str]], list[tuple[str, dict[str, Any]]]]]:
    """The shape table: (headers, rows, [(tag, step)]) per small table."""
    groups = []
    h = ["id", "q1", "q2", "q3"]
    r = [["1", "10", "", "30"], ["2", "", "", ""], ["3", "a b", "é", "😀"], ["", "", "x", ""], ["4", "0", "-0", "  "]]
    steps: list[tuple[str, dict[str, Any]]] = []
    for op in ("unpivot_columns", "unpivot_other_columns"):
        for cols in (["q1"], ["q2", "q1"], ["q3", "q1", "q2"], ["id"], ["id", "q1"], ["q1", "q2", "q3"],
                     ["id", "q1", "q2", "q3"], ["q1", "q1"], ["Q1"], ["q1 "], []):
            for at, va in (("a", "v"), ("id", "v"), ("a", "id"), ("q1", "v"), ("a", "q1"), ("a", "a"), (" a ", " v "),
                           ("", "v"), ("a", ""), ("é", "😀"), ("Attribute", "Value"), ("__rn", "v"), ("a b", "c d")):
                steps.append((f"{op} {cols} {at!r} {va!r}", {"op": op, "columns": cols, "attribute_name": at, "value_name": va}))
    groups.append((h, r, steps))
    for h2, r2 in ((["a"], []), (["a"], [[""]]), (["a", "b"], []), (["a", "b"], [["", ""]])):
        steps = []
        for op in ("unpivot_columns", "unpivot_other_columns", "transpose_table", "promote_headers", "demote_headers"):
            step: dict[str, Any] = {"op": op}
            if op.startswith("unpivot"):
                step.update(columns=["a"], attribute_name="at", value_name="va")
            steps.append((f"{op} {h2} {r2}", step))
        groups.append((h2, r2, steps))
    wide = [f"c{i}" for i in range(30)]
    groups.append((wide, [[("" if (i + j) % 7 == 0 else f"v{i}_{j}") for j in range(30)] for i in range(12)],
                   [("transpose wide", {"op": "transpose_table"})]))
    for n in (600, 512, 513):
        groups.append((["a", "b"], [[str(i), ""] for i in range(n)], [(f"transpose {n} rows", {"op": "transpose_table"})]))
    groups.append((["a", "b"], [["x", "x"], ["x", "x"]], [("transpose repeated cells", {"op": "transpose_table"})]))
    for cell in ["", "|", "||", "a|", "|a", "a||b", "x"]:
        groups.append((["k", "v", "w"], [["1", cell, "z"], ["2", "", "y"], ["3", "q|r", ""]],
                       [(f"split_rows {cell!r}", {"op": "split_column_to_rows", "column": "v", "delimiter": "|"})]))
    groups.append((["k", "v"], [["1", "|".join(str(i) for i in range(3000))]] * 3,
                   [("split_rows 9000 parts", {"op": "split_column_to_rows", "column": "v", "delimiter": "|"})]))
    steps = []
    for pos in ([0, 1], [0, 2], [0, 0], [1, 2], [0, -1], [0, 3, 2], [0, 1, 1], [0, 5, 10, 20], [0, 1000], [0, True],
                [0, 1.0], [0], [], list(range(13))):
        steps.append((f"positions {pos}", {"op": "split_column_by_positions", "column": "t", "positions": pos}))
    groups.append((["id", "t", "u"], [["1", "abcdef", "x"], ["2", "", "y"], ["3", "é́😀你好", ""]], steps))
    groups.append((["t"], [["x" * 600]], [
        ("positions 512", {"op": "split_column_by_positions", "column": "t", "positions": list(range(512))}),
        ("positions 513", {"op": "split_column_by_positions", "column": "t", "positions": list(range(513))}),
    ]))
    groups.append((["t", "t.2", "t.1"], [["abc", "1", "2"]], [
        ("positions clash", {"op": "split_column_by_positions", "column": "t", "positions": [0, 1]}),
    ]))
    return groups


def test_malformed_parameter_table_is_the_same_on_both_paths() -> None:
    """667 malformed-parameter steps: the store answers every one exactly as the engine does (value or error text)."""
    items = param_items()
    assert len(items) == 667
    assert Counter(i["step"]["op"] for i in items) == {
        "unpivot_columns": 3 * 33 + 1, "unpivot_other_columns": 3 * 33 + 1, "split_column_to_rows": 2 * 33 + 1,
        "split_column_by_positions": 2 * 33 + 1, "extract_text_by_delimiter": 4 * 33 + 1,
        "extract_text_between_delimiters": 5 * 33 + 1, "promote_headers": 33 + 1,
    }
    results = _run_items({"headers": PARAM_HEADERS, "rows": PARAM_ROWS}, items)["results"]
    by_id = {r["id"]: r for r in results}
    assert len(by_id) == 667
    not_same = {i: (r["status"], r.get("diff_reason") or r.get("refusal")) for i, r in by_id.items() if r["status"] != "same"}
    assert not_same == {}
    # 639 steps are errors in the engine and the store gives the engine's error text; 28 run on both paths
    assert sum(1 for r in by_id.values() if r.get("refusal")) == 639
    assert sum(1 for r in by_id.values() if not r.get("refusal")) == 28


def test_shape_table_is_the_same_or_refused_by_name() -> None:
    """336 shape steps: 323 the same on both paths, 13 refused by name for an output column called `__rn`."""
    total = 0
    statuses: Counter[str] = Counter()
    refused: list[tuple[str, str]] = []
    mirrored_errors = 0
    for headers, rows, steps in shape_groups():
        for (tag, _step), res in zip(steps, _run_group(headers, rows, steps)):
            total += 1
            statuses[res["status"]] += 1
            if res["status"] == "same" and res.get("refusal"):
                mirrored_errors += 1
            assert res["status"] in ("same", "refused"), (tag, res["status"], res.get("diff_reason"))
            if res["status"] == "refused":
                refused.append((tag, res["refusal"]))
    assert total == 336
    assert statuses == {"same": 323, "refused": 13}
    assert len(refused) == 13
    assert mirrored_errors == 203  # errors in the engine, the store gives the engine's error text; 120 steps run on both paths
    for tag, message in refused:
        assert "'__rn'" in message and "clashes with a name the store path uses" in message, (tag, message)
        assert "'__rn'" in tag, tag
